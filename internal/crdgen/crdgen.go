// Package crdgen writes the config CRDs' definitions (group golem.dev)
// from lib/api/v1alpha1's Go types. Each kind's spec becomes an OpenAPI
// schema, and a field's doc comment its description.
//
// The types are the source of truth. The compiler, lib/compile, does the
// validation. The schema gives only the shape, so a typo is refused at
// kubectl apply. Its test keeps deploy/charts/golem-control/crds current.
package crdgen

import (
	"cmp"
	"go/ast"
	"go/parser"
	"go/token"
	"path/filepath"
	"reflect"
	"strings"

	"sigs.k8s.io/yaml"

	v1 "github.com/chucklehead-dev/golem/lib/api/v1alpha1"
)

// Kinds are the CRDs, by kind: their spec types and plural names.
var Kinds = []struct {
	Kind, Plural string
	Spec         any
}{
	{v1.KindBackend, "backends", v1.BackendSpec{}},
	{v1.KindModelRoute, "modelroutes", v1.ModelRouteSpec{}},
	{v1.KindScopePolicy, "scopepolicies", v1.ScopePolicySpec{}},
	{v1.KindPriceList, "pricelists", v1.PriceListSpec{}},
}

// Docs reads the doc comments of the package's struct fields, from its
// source in dir: "Type.Field" to its text (the comment above the field,
// else the one after it).
func Docs(dir string) (map[string]string, error) {
	paths, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		return nil, err
	}
	fset := token.NewFileSet()
	out := map[string]string{}
	for _, path := range paths {
		if strings.HasSuffix(path, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, path, nil, parser.ParseComments)
		if err != nil {
			return nil, err
		}
		ast.Inspect(f, func(n ast.Node) bool {
			ts, ok := n.(*ast.TypeSpec)
			if !ok {
				return true
			}
			if st, ok := ts.Type.(*ast.StructType); ok {
				for _, fl := range st.Fields.List {
					text := cmp.Or(fl.Doc.Text(), fl.Comment.Text())
					for _, n := range fl.Names {
						out[ts.Name.Name+"."+n.Name] = clean(text)
					}
				}
			}
			return false
		})
	}
	return out, nil
}

// clean is a doc comment as one line.
func clean(s string) string { return strings.Join(strings.Fields(s), " ") }

// schema is t's OpenAPI v3 schema.
func schema(t reflect.Type, docs map[string]string) map[string]any {
	switch t.Kind() {
	case reflect.Pointer:
		return schema(t.Elem(), docs)
	case reflect.String:
		return map[string]any{"type": "string"}
	case reflect.Bool:
		return map[string]any{"type": "boolean"}
	case reflect.Int, reflect.Int32, reflect.Int64:
		return map[string]any{"type": "integer"}
	case reflect.Float32, reflect.Float64:
		return map[string]any{"type": "number"}
	case reflect.Slice:
		return map[string]any{"type": "array", "items": schema(t.Elem(), docs)}
	case reflect.Map:
		return map[string]any{"type": "object", "additionalProperties": schema(t.Elem(), docs)}
	case reflect.Struct:
		if t.PkgPath() == "time" {
			return map[string]any{"type": "string", "format": "date-time"}
		}
		props := map[string]any{}
		for i := range t.NumField() {
			f := t.Field(i)
			name, _, _ := strings.Cut(f.Tag.Get("json"), ",")
			if name == "-" || !f.IsExported() {
				continue
			}
			if name == "" {
				name = f.Name
			}
			p := schema(f.Type, docs)
			if d := docs[t.Name()+"."+f.Name]; d != "" {
				p["description"] = d
			}
			props[name] = p
		}
		return map[string]any{"type": "object", "properties": props}
	}
	return map[string]any{"x-kubernetes-preserve-unknown-fields": true}
}

// CRD is a kind's CustomResourceDefinition, as YAML.
func CRD(kind, plural string, spec any, docs map[string]string) ([]byte, error) {
	group, version, _ := strings.Cut(v1.APIVersion, "/")
	crd := map[string]any{
		"apiVersion": "apiextensions.k8s.io/v1",
		"kind":       "CustomResourceDefinition",
		"metadata":   map[string]any{"name": plural + "." + group},
		"spec": map[string]any{
			"group": group,
			"scope": "Namespaced",
			"names": map[string]any{"kind": kind, "plural": plural, "singular": strings.ToLower(kind), "listKind": kind + "List"},
			"versions": []any{map[string]any{
				"name": version, "served": true, "storage": true,
				"schema": map[string]any{"openAPIV3Schema": map[string]any{
					"type":       "object",
					"required":   []any{"spec"},
					"properties": map[string]any{"spec": schema(reflect.TypeOf(spec), docs)},
				}},
			}},
		},
	}
	b, err := yaml.Marshal(crd)
	if err != nil {
		return nil, err
	}
	return append([]byte("# Generated by internal/crdgen from lib/api/v1alpha1: do not edit.\n# GOLEM_UPDATE_CRDS=1 go test ./internal/crdgen/\n"), b...), nil
}
